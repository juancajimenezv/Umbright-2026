UPDATE l SET Error = 'CC no existe o no vigente en BDFlexline (CON_CCOSTO)'
  FROM #lista l
 WHERE l.CentroCosto IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM BDFlexline.flexline.GEN_TABCOD g
                    WHERE g.EMPRESA = @Empresa AND g.TIPO = 'CON_CCOSTO'
                      AND LTRIM(RTRIM(g.CODIGO)) = l.CentroCosto
                      AND ISNULL(g.VIGENCIA,'') <> 'N')

UPDATE l SET Error = ISNULL(l.Error + ' | ','') + 'Item no existe o no vigente en BDFlexline (CON_ITEM)'
  FROM #lista l
 WHERE NOT EXISTS (SELECT 1 FROM BDFlexline.flexline.GEN_TABCOD g
                    WHERE g.EMPRESA = @Empresa AND g.TIPO = 'CON_ITEM'
                      AND LTRIM(RTRIM(g.CODIGO)) = l.ItemGasto
                      AND ISNULL(g.VIGENCIA,'') <> 'N')

UPDATE l SET Error = ISNULL(l.Error + ' | ','') + 'Producto no existe o no vigente en PRODUCTO'
  FROM #lista l
 WHERE NOT EXISTS (SELECT 1 FROM flexline.PRODUCTO p
                    WHERE p.EMPRESA = @Empresa AND p.PRODUCTO = l.Producto
                      AND p.VIGENTE = 'S')

UPDATE l SET Error = ISNULL(l.Error + ' | ','') + 'CC + Item repetido en la lista'
  FROM #lista l
 WHERE l.CentroCosto IS NOT NULL
   AND EXISTS (SELECT 1 FROM #lista d
                WHERE d.CentroCosto = l.CentroCosto AND d.ItemGasto = l.ItemGasto
                  AND d.fila <> l.fila)

